export type IconName = keyof typeof ICONS;
export type IconProps = Omit<LucideProps, "ref"> & { name: IconName };

/** lucide's defaults (24px, stroke 2), with the theme's text colour when no `color` is given. */
export function Icon({ name, size = 24, strokeWidth = 2, color, ...rest }: IconProps) {
  const { colors } = useTheme();
  const Glyph: LucideIcon | undefined = ICONS[name];
  // The type makes an unregistered name a compile error; this only guards a name that arrives untyped
  // (e.g. from server data) so one bad string can't take a whole screen down.
  if (!Glyph) {
    if (__DEV__) console.warn(`Icon: "${name}" is not in the registry (components/core/Icon.tsx).`);
    return null;
  }
  return <Glyph size={size} strokeWidth={strokeWidth} color={color ?? colors.text} {...rest} />;
}
