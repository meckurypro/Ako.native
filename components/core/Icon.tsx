// (1.33.0, see ako/package.json); this is the same glyph set from
// lucide-react-native pinned to the same version, so an icon here is
// the same glyph art web shows in that slot.
//
// Names are lucide's own kebab-case names (`arrow-left`, `trash-2`,
// `more-horizontal`) — the kebab form of the identifier web imports — so a
// web `<Trash2 />` is `<Icon name="trash-2" />` here. Adding an icon means
// adding one import and one registry line below; `IconName` is derived from
// the registry, so a typo'd or unregistered name fails the typecheck.
//
// Why not the icon fonts this replaced (Material Community Icons, Feather):
// fonts can't do what web relies on — a filled active state (`fill`) and a
// per-icon `strokeWidth` (the tab bar's 2 / 1.75) — and MCI's drawing style
// differs from Lucide's, so the same slot rendered differently from web.
//
// Filled states follow web: pass `fill={active ? color : "none"}` (Heart,
// Bookmark, ThumbsDown, Rocket); there is no separate "-outline" glyph.
